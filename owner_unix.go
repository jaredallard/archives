//go:build unix

package archives

import (
	"io/fs"
	"syscall"
)

// fileOwner returns the user and group ID of the file described by fi.
func fileOwner(fi fs.FileInfo) (uid, gid int, ok bool) {
	st, ok := fi.Sys().(*syscall.Stat_t)
	if !ok {
		return 0, 0, false
	}
	return int(st.Uid), int(st.Gid), true
}
